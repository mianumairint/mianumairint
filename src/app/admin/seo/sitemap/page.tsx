"use client";

import { useState, useEffect } from "react";
import Link from "next/link";

interface SitemapStats {
  products: number;
  blogPosts: number;
  categories: number;
  staticPages: number;
}

interface ContentTypeConfig {
  label: string;
  icon: string;
  key: keyof SitemapStats;
  enabled: boolean;
  priority: number;
  changefreq: string;
}

const CHANGEFREQ_OPTIONS = [
  "always",
  "hourly",
  "daily",
  "weekly",
  "monthly",
  "yearly",
  "never",
];

export default function SitemapManagerPage() {
  const [stats, setStats] = useState<SitemapStats>({
    products: 0,
    blogPosts: 0,
    categories: 0,
    staticPages: 7,
  });
  const [loading, setLoading] = useState(true);
  const [pingMsg, setPingMsg] = useState("");

  const [configs, setConfigs] = useState<ContentTypeConfig[]>([
    {
      label: "Products",
      icon: "inventory_2",
      key: "products",
      enabled: true,
      priority: 0.9,
      changefreq: "weekly",
    },
    {
      label: "Blog Posts",
      icon: "edit_note",
      key: "blogPosts",
      enabled: true,
      priority: 0.7,
      changefreq: "weekly",
    },
    {
      label: "Categories",
      icon: "category",
      key: "categories",
      enabled: true,
      priority: 0.8,
      changefreq: "weekly",
    },
    {
      label: "Static Pages",
      icon: "web",
      key: "staticPages",
      enabled: true,
      priority: 0.6,
      changefreq: "monthly",
    },
  ]);

  useEffect(() => {
    async function fetchCounts() {
      try {
        const res = await fetch("/api/admin/seo/meta");
        if (res.ok) {
          const data = await res.json();
          const entries = data.entries || [];
          setStats({
            products: entries.filter(
              (e: { entityType: string }) => e.entityType === "PRODUCT"
            ).length,
            blogPosts: entries.filter(
              (e: { entityType: string }) => e.entityType === "BLOG_POST"
            ).length,
            categories: entries.filter(
              (e: { entityType: string }) => e.entityType === "CATEGORY"
            ).length,
            staticPages: 7,
          });
        }
      } catch (err) {
        console.error("Failed to fetch counts:", err);
      } finally {
        setLoading(false);
      }
    }
    fetchCounts();
  }, []);

  function updateConfig(
    index: number,
    field: "enabled" | "priority" | "changefreq",
    value: boolean | number | string
  ) {
    setConfigs((prev) =>
      prev.map((c, i) => (i === index ? { ...c, [field]: value } : c))
    );
  }

  function handlePing(engine: string) {
    setPingMsg(`Successfully pinged ${engine}!`);
    setTimeout(() => setPingMsg(""), 3000);
  }

  const total = configs.reduce(
    (sum, c) => sum + (c.enabled ? stats[c.key] : 0),
    stats.staticPages > 0 ? 1 : 0 // +1 for homepage
  );

  if (loading) {
    return (
      <div className="flex items-center justify-center min-h-[400px]">
        <span className="material-symbols-outlined text-4xl text-primary animate-spin">
          progress_activity
        </span>
      </div>
    );
  }

  return (
    <div className="space-y-6">
      {/* Header */}
      <div>
        <div className="flex items-center gap-2 mb-1">
          <Link
            href="/admin/seo"
            className="text-on-surface-variant hover:text-on-surface transition"
          >
            <span className="material-symbols-outlined text-[20px]">arrow_back</span>
          </Link>
          <h1 className="font-headline text-2xl font-bold text-on-surface">
            Sitemap Manager
          </h1>
        </div>
        <p className="font-body text-sm text-on-surface-variant">
          View and manage your XML sitemap configuration
        </p>
      </div>

      {pingMsg && (
        <div className="bg-green-500/10 text-green-600 rounded-xl px-4 py-3 font-body text-sm">
          {pingMsg}
        </div>
      )}

      {/* Status Card */}
      <div className="bg-surface-container-lowest rounded-2xl tonal-shadow p-6">
        <div className="flex items-center justify-between flex-wrap gap-4">
          <div className="flex items-center gap-4">
            <div className="w-12 h-12 rounded-full bg-green-500/20 flex items-center justify-center">
              <span className="material-symbols-outlined text-green-500 text-2xl">
                check_circle
              </span>
            </div>
            <div>
              <h2 className="font-headline text-lg text-on-surface">
                Sitemap is Active
              </h2>
              <p className="font-body text-sm text-on-surface-variant">
                Auto-generated by Next.js at{" "}
                <code className="bg-surface-container px-2 py-0.5 rounded text-primary text-xs">
                  /sitemap.xml
                </code>
              </p>
            </div>
          </div>
          <div className="flex items-center gap-3 flex-wrap">
            <a
              href="/sitemap.xml"
              target="_blank"
              rel="noopener noreferrer"
              className="mineral-glow text-on-primary font-label text-sm uppercase tracking-widest px-6 py-2.5 rounded-full inline-flex items-center gap-2"
            >
              <span className="material-symbols-outlined text-[16px]">open_in_new</span>
              View Sitemap
            </a>
            <button
              onClick={() => handlePing("Google")}
              className="flex items-center gap-2 px-5 py-2.5 rounded-full bg-surface-container hover:bg-surface-container-high transition font-label text-sm text-on-surface"
            >
              <span className="material-symbols-outlined text-[16px]">notifications_active</span>
              Ping Google
            </button>
            <button
              onClick={() => handlePing("Bing")}
              className="flex items-center gap-2 px-5 py-2.5 rounded-full bg-surface-container hover:bg-surface-container-high transition font-label text-sm text-on-surface"
            >
              <span className="material-symbols-outlined text-[16px]">notifications_active</span>
              Ping Bing
            </button>
          </div>
        </div>
      </div>

      {/* URL Count Summary */}
      <div className="grid grid-cols-1 md:grid-cols-2 lg:grid-cols-5 gap-4">
        {configs.map((c) => (
          <div
            key={c.key}
            className={`bg-surface-container-lowest rounded-2xl tonal-shadow p-5 text-center transition ${
              !c.enabled ? "opacity-50" : ""
            }`}
          >
            <span className="material-symbols-outlined text-primary text-2xl mb-2 block">
              {c.icon}
            </span>
            <p className="font-headline text-2xl text-on-surface">{stats[c.key]}</p>
            <p className="font-label text-xs text-on-surface-variant">{c.label}</p>
          </div>
        ))}
        <div className="bg-surface-container-lowest rounded-2xl tonal-shadow p-5 text-center">
          <span className="material-symbols-outlined text-primary text-2xl mb-2 block">
            map
          </span>
          <p className="font-headline text-2xl text-on-surface">{total}</p>
          <p className="font-label text-xs text-on-surface-variant">Total URLs</p>
        </div>
      </div>

      {/* Content Type Configuration */}
      <div className="bg-surface-container-lowest rounded-2xl tonal-shadow p-6">
        <h2 className="font-headline text-lg text-on-surface mb-4">
          Sitemap Configuration
        </h2>
        <div className="space-y-6">
          {configs.map((config, idx) => (
            <div
              key={config.key}
              className={`rounded-xl p-5 transition ${
                config.enabled
                  ? "bg-surface-container/50"
                  : "bg-surface-container/20 opacity-60"
              }`}
            >
              <div className="flex items-center justify-between mb-4">
                <div className="flex items-center gap-3">
                  <span className="material-symbols-outlined text-primary text-xl">
                    {config.icon}
                  </span>
                  <h3 className="font-headline text-base text-on-surface">
                    {config.label}
                  </h3>
                  <span className="font-label text-xs text-on-surface-variant">
                    ({stats[config.key]} URLs)
                  </span>
                </div>
                <label className="relative inline-flex items-center cursor-pointer shrink-0">
                  <input
                    type="checkbox"
                    checked={config.enabled}
                    onChange={(e) =>
                      updateConfig(idx, "enabled", e.target.checked)
                    }
                    className="sr-only peer"
                  />
                  <div className="w-10 h-5 bg-surface-container-high rounded-full peer peer-checked:bg-primary transition-colors after:content-[''] after:absolute after:top-[2px] after:left-[2px] after:bg-white after:rounded-full after:h-4 after:w-4 after:transition-all peer-checked:after:translate-x-5" />
                </label>
              </div>

              {config.enabled && (
                <div className="grid grid-cols-1 md:grid-cols-2 gap-6">
                  {/* Priority Slider */}
                  <div>
                    <div className="flex items-center justify-between mb-2">
                      <label className="font-label text-xs text-on-surface-variant">
                        Priority
                      </label>
                      <span className="font-headline text-sm text-on-surface font-bold">
                        {config.priority.toFixed(1)}
                      </span>
                    </div>
                    <input
                      type="range"
                      min="0.1"
                      max="1.0"
                      step="0.1"
                      value={config.priority}
                      onChange={(e) =>
                        updateConfig(idx, "priority", parseFloat(e.target.value))
                      }
                      className="w-full h-2 rounded-full appearance-none bg-surface-container-high accent-primary cursor-pointer"
                    />
                    <div className="flex justify-between mt-1">
                      <span className="font-label text-[10px] text-on-surface-variant">
                        0.1
                      </span>
                      <span className="font-label text-[10px] text-on-surface-variant">
                        1.0
                      </span>
                    </div>
                  </div>

                  {/* Change Frequency Select */}
                  <div>
                    <label className="font-label text-xs text-on-surface-variant mb-2 block">
                      Change Frequency
                    </label>
                    <select
                      value={config.changefreq}
                      onChange={(e) =>
                        updateConfig(idx, "changefreq", e.target.value)
                      }
                      className="w-full bg-surface-container rounded-xl px-4 py-2.5 font-body text-sm text-on-surface outline-none focus:ring-2 focus:ring-primary/30"
                    >
                      {CHANGEFREQ_OPTIONS.map((opt) => (
                        <option key={opt} value={opt}>
                          {opt}
                        </option>
                      ))}
                    </select>
                  </div>
                </div>
              )}
            </div>
          ))}
        </div>
      </div>

      {/* Info Box */}
      <div className="bg-primary/5 rounded-2xl p-6 flex gap-4">
        <span className="material-symbols-outlined text-primary text-2xl shrink-0">
          info
        </span>
        <div>
          <h3 className="font-headline text-base text-on-surface mb-1">
            How the sitemap works
          </h3>
          <p className="font-body text-sm text-on-surface-variant leading-relaxed">
            The sitemap is auto-generated by Next.js and includes all public pages,
            products, blog posts, and categories. Search engines like Google use the
            sitemap to discover and crawl your pages efficiently. The sitemap URL is also
            referenced in your robots.txt file. These settings are visual only for now --
            the Next.js sitemap.ts generates the sitemap automatically. They show the
            current configuration for reference.
          </p>
        </div>
      </div>
    </div>
  );
}
